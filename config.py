def _norm(name: object) -> str:
    """Нормализира име на обект за устойчиво сравнение (интервали, регистър)."""
    return re.sub(r"\s+", " ", str(name)).strip().casefold()


_OBJECT_CITY_NORM = {_norm(k): v for k, v in OBJECT_CITY.items()}


def city_for(object_name: object) -> str | None:
    """Връща региона/града за даден обект, устойчиво на регистър и интервали."""
    return _OBJECT_CITY_NORM.get(_norm(object_name))
